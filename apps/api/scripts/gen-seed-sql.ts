// Generates db/seed.sql: the reference data (exercises, routines, days, slots) as INSERT statements
// for `wrangler d1 execute DB --file db/seed.sql`. It runs the same `seedReferenceData` used by tests
// against an in-memory database built from the real migrations, then dumps the four tables.
//
//   pnpm --filter @gym-up/api db:seed-sql

import Database from 'better-sqlite3';
import { drizzle } from 'drizzle-orm/better-sqlite3';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as schema from '../db/schema';
import { seedReferenceData } from '../db/seed';
import type { Db } from '../src/lib/db/client';

const TABLES = ['exercises', 'routines', 'routine_days', 'routine_exercises'] as const;

const sqlite = new Database(':memory:');
sqlite.pragma('foreign_keys = ON');
const dir = join(import.meta.dirname, '..', 'db', 'migrations');
for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
  sqlite.exec(readFileSync(join(dir, file), 'utf8'));
}
await seedReferenceData(drizzle(sqlite, { schema }) as unknown as Db);

const quote = (v: unknown): string =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

const lines = ['-- Generated by scripts/gen-seed-sql.ts. Do not edit by hand.'];
for (const table of TABLES) {
  const rows = sqlite.prepare(`SELECT * FROM ${table}`).all() as Record<string, unknown>[];
  for (const row of rows) {
    const cols = Object.keys(row);
    lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => quote(row[c])).join(', ')});`);
  }
}
writeFileSync(join(import.meta.dirname, '..', 'db', 'seed.sql'), lines.join('\n') + '\n');
console.log(`db/seed.sql: ${lines.length - 1} statements`);
